export function searchEmojis(query, limit = 128) {
  if (!query || typeof query !== 'string') return COMPOSER_EMOJIS.slice(0, limit);
  const q = query.trim().toLowerCase();
  if (!q) return COMPOSER_EMOJIS.slice(0, limit);
  const results = [];
  const seen = new Set();
  for (const item of EMOJI_DATA) {
    if (results.length >= limit) break;
    if (seen.has(item.e)) continue;
    const hit =
      item.e.includes(q) ||
      item.keywords.some((k) => k.includes(q) || q.includes(k));
    if (hit) {
      seen.add(item.e);
      results.push(item.e);
    }
  }
  return results;
}

export function getRecentEmojis() {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    const list = raw ? JSON.parse(raw) : [];
    return Array.isArray(list) ? list.filter((e) => typeof e === 'string') : [];
  } catch {
    return [];
  }
}

export function pushRecentEmoji(emoji) {
  if (!emoji || typeof emoji !== 'string') return;
  try {
    const prev = getRecentEmojis().filter((e) => e !== emoji);
    const next = [emoji, ...prev].slice(0, RECENT_LIMIT);
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    // ignore quota / private mode
  }
}
